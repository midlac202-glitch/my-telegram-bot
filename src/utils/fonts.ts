export function convertText(text: string, style: string): string {

  if (['strikethrough', 'underlined', 'wavy_underline', 'slash'].includes(style)) {
    const symbolMap: Record<string, string> = {
      strikethrough: '\u0336',
      underlined: '\u0332',
      wavy_underline: '\u0330',
      slash: '\u0337'
    };
    const mark = symbolMap[style];
    return text.split('').map(char => char + mark).join('');
  }

  const targetFont = fontMaps[style];

  if (!targetFont) return text;

  const styledArray = Array.from(targetFont);

  return text
    .split('')
    .map(char => {
      
      const index = NORMAL.indexOf(char);
      return index !== -1 ? styledArray[index] : char;
    })
    .join('');
}